"""## 2) تحميل نموذج TTS العربي"""

import torch, numpy as np, re, soundfile as sf
from transformers import VitsModel, AutoTokenizer
from IPython.display import Audio, display

MODEL_NAME = "facebook/mms-tts-ara"
device = "cuda" if torch.cuda.is_available() else "cpu"
tts_tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
tts_model = VitsModel.from_pretrained(MODEL_NAME).to(device)
tts_model.eval()
sample_rate = int(tts_model.config.sampling_rate)
print("Device:", device, "| Sample rate:", sample_rate)

