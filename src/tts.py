"""## 4) تنظيف النص وتقسيمه لجمل قصيرة"""

def clean_for_speech(text):
    text = re.sub(r"\\[S\\d+\\]", "", str(text))  # إزالة رموز citations
    text = re.sub(r"(?m)^\\s*[-•]\\s*", "", text)
    text = re.sub(r"\\s+", " ", text).strip()
    return text

def split_sentences(text, max_chars=220):
    text = clean_for_speech(text)
    pieces = re.split(r"(?<=[.!؟?])\\s+", text)
    result, current = [], ""
    for p in pieces:
        if not p:
            continue
        if len(current) + len(p) + 1 <= max_chars:
            current = (current + " " + p).strip()
        else:
            if current: result.append(current)
            current = p
    if current: result.append(current)
    return result

sentences = split_sentences(digest_text)
sentences

"""## 5) توليد الصوت"""

def synthesize_arabic(text, output_path="digest.wav"):
    sentences = split_sentences(text)
    audio_parts = []
    for sentence in sentences:
        inputs = tts_tokenizer(sentence, return_tensors="pt")
        inputs = {k:v.to(device) for k,v in inputs.items()}
        with torch.no_grad():
            waveform = tts_model(**inputs).waveform.squeeze().cpu().numpy()
        audio_parts.append(waveform.astype(np.float32))
        # فاصل صمت قصير بين الجمل
        audio_parts.append(np.zeros(int(sample_rate * 0.25), dtype=np.float32))
    if not audio_parts:
        raise ValueError("النص فارغ بعد التنظيف.")
    audio = np.concatenate(audio_parts)
    sf.write(output_path, audio, sample_rate)
    return output_path, audio

wav_path, audio = synthesize_arabic(digest_text)
print("Saved:", wav_path, "| Duration:", round(len(audio)/sample_rate, 2), "seconds")
display(Audio(audio, rate=sample_rate))

