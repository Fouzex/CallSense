"""## 3) قراءة البيانات وفحصها"""

import pandas as pd

df = pd.read_csv(CSV_PATH)

# التأكد من وجود الأعمدة المطلوبة في الملف الجديد
required = {"call_id", "whisper_transcript"}
missing = required - set(df.columns)

if missing:
    raise ValueError(
        f"الأعمدة المطلوبة غير موجودة: {missing}. "
        f"الأعمدة الموجودة: {list(df.columns)}"
    )

# حذف الصفوف التي لا تحتوي على نص من Whisper
df = df.dropna(subset=["whisper_transcript"]).copy()

# تنظيف النصوص
df["whisper_transcript"] = (
    df["whisper_transcript"].astype(str).str.strip()
)

df = df[df["whisper_transcript"].ne("")].reset_index(drop=True)

# توحيد أسماء الأعمدة لتتوافق مع بقية أكواد المشروع
df["transcript"] = df["whisper_transcript"]
df["audio_id"] = df["call_id"].astype(str)

print("عدد النصوص:", len(df))
print("الأعمدة:", list(df.columns))

display(df.head(197))

"""## 4) تحميل نموذج embeddings متعدد اللغات"""

import torch, numpy as np, random
from sentence_transformers import SentenceTransformer

SEED = 42
random.seed(SEED); np.random.seed(SEED); torch.manual_seed(SEED)
EMBED_MODEL = "intfloat/multilingual-e5-base"
device = "cuda" if torch.cuda.is_available() else "cpu"
print("Device:", device)

embedder = SentenceTransformer(EMBED_MODEL, device=device)
# E5 يتوقع prefix passage للنصوص و query للسؤال
passages = ["passage: " + t for t in df["transcript"].tolist()]
embeddings = embedder.encode(
    passages, batch_size=16, show_progress_bar=True,
    convert_to_numpy=True, normalize_embeddings=True
)
print("Embedding matrix:", embeddings.shape)

"""## 5) دالة البحث"""

def search_calls(query, top_k=5, group=None, dataset=None):
    q = embedder.encode(
        ["query: " + query],
        convert_to_numpy=True,
        normalize_embeddings=True
    )[0]
    scores = embeddings @ q
    results = df.copy()
    results["score"] = scores
    if group is not None and "group" in results.columns:
        results = results[results["group"].astype(str).str.lower() == str(group).lower()]
    if dataset is not None and "dataset" in results.columns:
        results = results[results["dataset"].astype(str).str.lower() == str(dataset).lower()]
    return results.sort_values("score", ascending=False).head(top_k)

question = "عميل يشتكي من مشكلة في الفاتورة"
hits = search_calls(question, top_k=5)
display(hits[[c for c in ["audio_id","dataset","group","score","transcript"] if c in hits.columns]])

"""## 6) جرّبي أسئلتك"""

test_queries = [
    "مشكلة في الفاتورة أو مبلغ غير صحيح",
    "العميل يواجه مشكلة تقنية في الخدمة",
    "طلب إلغاء أو إيقاف الاشتراك",
    "customer complaint about billing",
]
for q in test_queries:
    print("\\nQUESTION:", q)
    display(search_calls(q, top_k=3)[[c for c in ["audio_id","group","score","transcript"] if c in df.columns or c=="score"]])

