"""## 3) تحميل البيانات ونموذج الاسترجاع"""

import pandas as pd
import numpy as np
import torch
import random
from sentence_transformers import SentenceTransformer

SEED = 42
random.seed(SEED)
np.random.seed(SEED)
torch.manual_seed(SEED)

# قراءة الملف الجديد
df = pd.read_csv(CSV_PATH)

# التأكد من الأعمدة المطلوبة
required = {"call_id", "whisper_transcript"}
missing = required - set(df.columns)

if missing:
    raise ValueError(
        f"الأعمدة المطلوبة غير موجودة: {missing}. "
        f"الأعمدة الموجودة: {list(df.columns)}"
    )

# تنظيف النصوص
df = df.dropna(subset=["whisper_transcript"]).copy()
df["transcript"] = df["whisper_transcript"].astype(str).str.strip()

df = df[df["transcript"].ne("")].reset_index(drop=True)

# استخدام call_id كمعرّف للمصدر
df["audio_id"] = df["call_id"].astype(str)

# تحميل نموذج التضمين
EMBED_MODEL = "intfloat/multilingual-e5-base"
device = "cuda" if torch.cuda.is_available() else "cpu"

embedder = SentenceTransformer(EMBED_MODEL, device=device)

# إنشاء embeddings
embeddings = embedder.encode(
    ["passage: " + x for x in df["transcript"]],
    batch_size=16,
    show_progress_bar=True,
    convert_to_numpy=True,
    normalize_embeddings=True
)

# دالة البحث عن المكالمات الأكثر صلة
def retrieve(query, k=8):
    q = embedder.encode(
        ["query: " + query],
        convert_to_numpy=True,
        normalize_embeddings=True
    )[0]

    scores = embeddings @ q
    idx = np.argsort(scores)[::-1][:k]

    return [
        {
            "audio_id": df.iloc[i]["audio_id"],
            "text": df.iloc[i]["transcript"],
            "score": float(scores[i]),
            "dialect": str(df.iloc[i].get("dialect", ""))
        }
        for i in idx
    ]

# تجربة البحث
hits = retrieve("شكاوى العملاء عن الفواتير", k=8)

for i, h in enumerate(hits, 1):
    print(
        f"[S{i}] call_id={h['audio_id']} "
        f"score={h['score']:.3f}\n"
        f"{h['text']}\n"
    )

"""## 4) تحميل نموذج اللغة لتوليد الملخص"""

from transformers import AutoTokenizer, AutoModelForCausalLM
LLM_NAME = "Qwen/Qwen2.5-3B-Instruct"
tokenizer = AutoTokenizer.from_pretrained(LLM_NAME)
llm = AutoModelForCausalLM.from_pretrained(
    LLM_NAME,
    torch_dtype=torch.float16 if torch.cuda.is_available() else torch.float32,
    device_map="auto"
)

"""## 5) إنشاء ملخص grounded مع مصادر"""

def make_grounded_digest(query, k=8, max_new_tokens=350):
    sources = retrieve(query, k=k)
    source_block = "\\n\\n".join(
        f"[S{i}] audio_id={h['audio_id']}\\nالنص: {h['text']}"
        for i,h in enumerate(sources, 1)
    )
    system = (
        "أنت مساعد يكتب ملخصًا لمشرف مركز اتصال باللغة العربية. "
        "استخدم المعلومات الموجودة في المصادر فقط. "
        "لا تستنتج سببًا أو نتيجة غير مذكورة. "
        "إذا لم تكفِ المصادر، قل إن المعلومات غير كافية. "
        "اكتب 3 إلى 5 نقاط موجزة، وكل نقطة يجب أن تنتهي باستشهاد مثل [S1]. "
        "لا تخترع أرقام تسجيلات أو استشهادات."
    )
    user = f"موضوع الملخص: {query}\\n\\nالمصادر المتاحة:\\n{source_block}\\n\\nاكتب الملخص."
    messages = [{"role":"system","content":system},{"role":"user","content":user}]
    prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer(prompt, return_tensors="pt").to(llm.device)
    with torch.no_grad():
        output = llm.generate(
            **inputs, max_new_tokens=max_new_tokens,
            do_sample=False, repetition_penalty=1.05,
            pad_token_id=tokenizer.eos_token_id
        )
    generated = output[0][inputs["input_ids"].shape[1]:]
    digest = tokenizer.decode(generated, skip_special_tokens=True).strip()
    return digest, sources

digest, sources = make_grounded_digest("أبرز شكاوى العملاء المتعلقة بالفواتير")
print(digest)

"""## 6) التحقق الآلي من أن الاستشهادات تشير إلى مصادر موجودة"""

import re
def check_citations(digest, sources):
    valid = {f"S{i}" for i in range(1, len(sources)+1)}
    found = re.findall(r"\\[(S\\d+)\\]", digest)
    invalid = sorted(set(found) - valid)
    missing = not found
    return {
        "citations_found": found,
        "invalid_citations": invalid,
        "has_at_least_one_citation": not missing,
        "citation_ids_to_audio": {
            f"S{i}": h["audio_id"] for i,h in enumerate(sources,1)
        }
    }

check = check_citations(digest, sources)
print(check)

"""## 7) عرض النصوص التي استند إليها الملخص وحفظه"""

# عرض المصادر التي استخدمها التلخيص
for i, h in enumerate(sources, 1):
    print(
        f"[S{i}] -> call_id={h['audio_id']} "
        f"| dialect={h.get('dialect', '')}"
    )
    print(h["text"], "\n")

# حفظ التلخيص في ملف نصي
with open("digest.txt", "w", encoding="utf-8") as f:
    f.write(digest)

