"""## 8) تجربة baseline بدون استرجاع (اختياري)
للمقارنة، يمكن توليد رد من النموذج بدون تزويده بمصادر. لا تستخدمي هذا الرد كملخص موثّق؛ هو baseline فقط.
"""

def llm_only_baseline(query, max_new_tokens=250):
    messages = [
        {"role":"system","content":"اكتب ردًا موجزًا بالعربية. لا تدّعِ أنك اطلعت على بيانات مكالمات فعلية."},
        {"role":"user","content":f"اكتب ملخصًا عامًا حول: {query}"}
    ]
    prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer(prompt, return_tensors="pt").to(llm.device)
    with torch.no_grad():
        out = llm.generate(**inputs, max_new_tokens=max_new_tokens, do_sample=False,
                           pad_token_id=tokenizer.eos_token_id)
    return tokenizer.decode(out[0][inputs["input_ids"].shape[1]:], skip_special_tokens=True)

print(llm_only_baseline("أبرز مشاكل الفواتير في مركز الاتصال"))

